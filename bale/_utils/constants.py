from enum import Enum, auto
from typing import Any, Type, TypeVar

E = TypeVar("E", bound=Enum)

__all__ = ("parse_enum", "ContextDataScope")


def parse_enum(value: Any, enum_cls: Type[E]) -> E | Any:
    try:
        return enum_cls(value)
    except (ValueError, TypeError):
        return value


class ContextDataScope(Enum):
    USER = auto()
    CHAT = auto()
    BOT = auto()
